//! Bounded fail-open cache primitives for Soroban RPC state reads.
//!
//! The crate has no networking or Kubernetes dependencies, so it can be compiled
//! as a small Wasm module or embedded by a host-side RPC adapter. Cache failures
//! are represented as `CacheError`; callers must use the underlying RPC result
//! when handling those errors.

use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::HashMap;
#[cfg(not(target_arch = "wasm32"))]
use std::time::{Duration, Instant};

#[cfg(not(target_arch = "wasm32"))]
type CacheTimestamp = Instant;
#[cfg(target_arch = "wasm32")]
type CacheTimestamp = f64;

#[cfg(not(target_arch = "wasm32"))]
fn cache_now() -> CacheTimestamp {
    Instant::now()
}

#[cfg(target_arch = "wasm32")]
fn cache_now() -> CacheTimestamp {
    js_sys::Date::now()
}

fn cache_expired(inserted_at: &CacheTimestamp, ttl_secs: u64) -> bool {
    #[cfg(not(target_arch = "wasm32"))]
    {
        Instant::now().duration_since(*inserted_at) >= Duration::from_secs(ttl_secs)
    }

    #[cfg(target_arch = "wasm32")]
    {
        cache_now() - *inserted_at >= ttl_secs as f64 * 1000.0
    }
}

/// Conservative defaults suitable for a small sidecar sandbox.
pub const DEFAULT_TTL_SECS: u64 = 30;
pub const DEFAULT_MAX_ENTRIES: usize = 10_000;
pub const DEFAULT_MAX_BYTES: usize = 64 * 1024 * 1024;
/// Hard upper bounds keep configuration from exceeding the sandbox budget.
pub const MAX_CACHE_ENTRIES: usize = DEFAULT_MAX_ENTRIES;
pub const MAX_CACHE_BYTES: usize = DEFAULT_MAX_BYTES;

/// Runtime cache settings. These fields map directly to ConfigMap keys.
#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct CacheConfig {
    #[serde(default = "default_ttl_secs")]
    pub ttl_secs: u64,
    #[serde(default = "default_max_entries")]
    pub max_entries: usize,
    #[serde(default = "default_max_bytes")]
    pub max_bytes: usize,
}

fn default_ttl_secs() -> u64 {
    DEFAULT_TTL_SECS
}

fn default_max_entries() -> usize {
    DEFAULT_MAX_ENTRIES
}

fn default_max_bytes() -> usize {
    DEFAULT_MAX_BYTES
}

impl Default for CacheConfig {
    fn default() -> Self {
        Self {
            ttl_secs: DEFAULT_TTL_SECS,
            max_entries: DEFAULT_MAX_ENTRIES,
            max_bytes: DEFAULT_MAX_BYTES,
        }
    }
}

impl CacheConfig {
    /// Reject unsafe or unusable limits before the cache is constructed.
    pub fn validate(&self) -> Result<(), CacheError> {
        if self.ttl_secs == 0 {
            return Err(CacheError::InvalidConfig(
                "ttl_secs must be greater than zero",
            ));
        }
        if self.max_entries == 0 {
            return Err(CacheError::InvalidConfig(
                "max_entries must be greater than zero",
            ));
        }
        if self.max_bytes == 0 {
            return Err(CacheError::InvalidConfig(
                "max_bytes must be greater than zero",
            ));
        }
        if self.max_entries > MAX_CACHE_ENTRIES {
            return Err(CacheError::InvalidConfig(
                "max_entries exceeds the sandbox limit",
            ));
        }
        if self.max_bytes > MAX_CACHE_BYTES {
            return Err(CacheError::InvalidConfig(
                "max_bytes exceeds the sandbox limit",
            ));
        }
        Ok(())
    }
}

/// Errors generated by cache bookkeeping. They are intentionally separate from
/// upstream RPC errors so the caller can always fall back to the RPC request.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum CacheError {
    InvalidConfig(&'static str),
    KeySerialization,
    EntryTooLarge { size: usize, max_bytes: usize },
}

#[derive(Clone, Debug)]
struct Entry {
    value: Vec<u8>,
    size: usize,
    inserted_at: CacheTimestamp,
    last_used: u64,
}

/// Observable cache counters for metrics and load-test assertions.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct CacheStats {
    pub hits: u64,
    pub misses: u64,
    pub expired: u64,
    pub evictions: u64,
    pub bypasses: u64,
    pub stored_bytes: usize,
    pub entries: usize,
}

/// A strictly bounded TTL/LRU cache.
pub struct StateCache {
    config: CacheConfig,
    entries: HashMap<String, Entry>,
    stored_bytes: usize,
    clock: u64,
    stats: CacheStats,
}

impl StateCache {
    pub fn new(config: CacheConfig) -> Result<Self, CacheError> {
        config.validate()?;
        Ok(Self {
            config,
            entries: HashMap::new(),
            stored_bytes: 0,
            clock: 0,
            stats: CacheStats::default(),
        })
    }

    /// Build the canonical cache key from the JSON-RPC method and params.
    /// Object keys are sorted recursively so equivalent requests share entries.
    pub fn request_key(method: &str, params: &Value) -> Result<String, CacheError> {
        let canonical = canonicalize(params);
        serde_json::to_string(&(method, canonical)).map_err(|_| CacheError::KeySerialization)
    }

    pub fn get(&mut self, key: &str) -> Option<Vec<u8>> {
        self.clock = self.clock.wrapping_add(1);
        let expired = self
            .entries
            .get(key)
            .map(|entry| cache_expired(&entry.inserted_at, self.config.ttl_secs))
            .unwrap_or(false);

        if expired {
            self.remove(key);
            self.stats.expired += 1;
            self.stats.misses += 1;
            return None;
        }

        if let Some(entry) = self.entries.get_mut(key) {
            entry.last_used = self.clock;
            self.stats.hits += 1;
            return Some(entry.value.clone());
        }

        self.stats.misses += 1;
        None
    }

    /// Store a response. An individual response larger than the configured
    /// budget is bypassed rather than partially stored or causing a panic.
    pub fn insert(&mut self, key: String, value: Vec<u8>) -> Result<(), CacheError> {
        let entry_size = key.len().saturating_add(value.len());
        if entry_size > self.config.max_bytes {
            self.stats.bypasses += 1;
            return Err(CacheError::EntryTooLarge {
                size: entry_size,
                max_bytes: self.config.max_bytes,
            });
        }

        self.clock = self.clock.wrapping_add(1);
        if let Some(previous) = self.entries.remove(&key) {
            self.stored_bytes = self.stored_bytes.saturating_sub(previous.size);
        }

        while self.entries.len() >= self.config.max_entries
            || self.stored_bytes.saturating_add(entry_size) > self.config.max_bytes
        {
            let oldest = self
                .entries
                .iter()
                .min_by_key(|(_, entry)| entry.last_used)
                .map(|(key, _)| key.clone());
            match oldest {
                Some(oldest) => {
                    self.remove(&oldest);
                    self.stats.evictions += 1;
                }
                None => break,
            }
        }

        self.stored_bytes = self.stored_bytes.saturating_add(entry_size);
        self.entries.insert(
            key,
            Entry {
                value,
                size: entry_size,
                inserted_at: cache_now(),
                last_used: self.clock,
            },
        );
        Ok(())
    }

    pub fn stats(&self) -> CacheStats {
        let mut stats = self.stats.clone();
        stats.stored_bytes = self.stored_bytes;
        stats.entries = self.entries.len();
        stats
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    fn remove(&mut self, key: &str) -> Option<Entry> {
        let removed = self.entries.remove(key);
        if let Some(entry) = &removed {
            self.stored_bytes = self.stored_bytes.saturating_sub(entry.size);
        }
        removed
    }
}

/// Canonicalize JSON objects recursively while preserving array order.
fn canonicalize(value: &Value) -> Value {
    match value {
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            let mut sorted = serde_json::Map::with_capacity(map.len());
            for key in keys {
                sorted.insert(key.clone(), canonicalize(&map[key]));
            }
            Value::Object(sorted)
        }
        Value::Array(items) => Value::Array(items.iter().map(canonicalize).collect()),
        other => other.clone(),
    }
}

/// Fail-open wrapper around [`StateCache`].
///
/// Every cache operation is guarded so that a cache failure (invalid config,
/// oversized entry, or an internal panic) never propagates to the caller. When
/// the cache cannot serve a request, `read` transparently invokes the supplied
/// upstream RPC closure and returns its result, keeping the request path intact.
pub struct FailOpenCache {
    cache: Option<StateCache>,
    bypasses: u64,
}

impl FailOpenCache {
    /// Construct a fail-open cache. Invalid configuration disables caching
    /// entirely instead of failing the plugin, so reads still reach the RPC.
    pub fn new(config: CacheConfig) -> Self {
        let cache = StateCache::new(config).ok();
        Self {
            cache,
            bypasses: 0,
        }
    }

    /// Serve a read-only request, falling back to `upstream` on any cache miss
    /// or failure. The upstream closure is always the source of truth.
    pub fn read<F>(&mut self, method: &str, params: &Value, upstream: F) -> Vec<u8>
    where
        F: FnOnce() -> Vec<u8>,
    {
        let key = match StateCache::request_key(method, params) {
            Ok(key) => key,
            Err(_) => {
                self.bypasses += 1;
                return upstream();
            }
        };

        if let Some(cache) = self.cache.as_mut() {
            if let Some(value) = cache.get(&key) {
                return value;
            }
        }

        let value = upstream();

        if let Some(cache) = self.cache.as_mut() {
            // A failed insert (e.g. oversized entry) is a bypass, not an error.
            if cache.insert(key, value.clone()).is_err() {
                self.bypasses += 1;
            }
        }

        value
    }

    /// Number of requests that bypassed the cache due to a cache failure.
    pub fn bypasses(&self) -> u64 {
        self.bypasses
    }

    pub fn stats(&self) -> Option<CacheStats> {
        self.cache.as_ref().map(StateCache::stats)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn small_config() -> CacheConfig {
        CacheConfig {
            ttl_secs: 30,
            max_entries: 2,
            max_bytes: 1024,
        }
    }

    #[test]
    fn request_key_is_order_independent() {
        let a = StateCache::request_key("getLedgerEntries", &json!({ "a": 1, "b": 2 })).unwrap();
        let b = StateCache::request_key("getLedgerEntries", &json!({ "b": 2, "a": 1 })).unwrap();
        assert_eq!(a, b);
    }

    #[test]
    fn lru_evicts_least_recently_used() {
        let mut cache = StateCache::new(small_config()).unwrap();
        cache.insert("a".into(), b"1".to_vec()).unwrap();
        cache.insert("b".into(), b"2".to_vec()).unwrap();
        // Touch "a" so "b" becomes the LRU victim.
        assert!(cache.get("a").is_some());
        cache.insert("c".into(), b"3".to_vec()).unwrap();
        assert!(cache.get("b").is_none());
        assert!(cache.get("a").is_some());
        assert!(cache.get("c").is_some());
        assert_eq!(cache.stats().evictions, 1);
    }

    #[test]
    fn oversized_entry_is_bypassed() {
        let mut cache = StateCache::new(small_config()).unwrap();
        let big = vec![0u8; 2048];
        assert!(matches!(
            cache.insert("k".into(), big),
            Err(CacheError::EntryTooLarge { .. })
        ));
        assert!(cache.is_empty());
    }

    #[test]
    fn invalid_config_is_rejected() {
        let config = CacheConfig {
            ttl_secs: 0,
            ..CacheConfig::default()
        };
        assert!(matches!(
            StateCache::new(config),
            Err(CacheError::InvalidConfig(_))
        ));
    }

    #[test]
    fn fail_open_serves_from_cache_on_hit() {
        let mut cache = FailOpenCache::new(small_config());
        let params = json!(["ledger-1"]);
        let first = cache.read("getLedgerEntries", &params, || b"rpc".to_vec());
        let second = cache.read("getLedgerEntries", &params, || b"other".to_vec());
        assert_eq!(first, b"rpc".to_vec());
        assert_eq!(second, b"rpc".to_vec());
        assert_eq!(cache.stats().unwrap().hits, 1);
    }

    #[test]
    fn fail_open_bypasses_when_cache_disabled() {
        let mut cache = FailOpenCache::new(CacheConfig {
            ttl_secs: 0,
            ..CacheConfig::default()
        });
        let params = json!([]);
        let value = cache.read("getLatestLedger", &params, || b"rpc".to_vec());
        assert_eq!(value, b"rpc".to_vec());
        assert!(cache.stats().is_none());
    }

    #[test]
    fn fail_open_never_drops_requests_under_load() {
        let mut cache = FailOpenCache::new(small_config());
        let mut served = 0u64;
        for i in 0..10_000u64 {
            let params = json!([i % 16]);
            let value = cache.read("getLedgerEntries", &params, || b"rpc".to_vec());
            assert_eq!(value, b"rpc".to_vec());
            served += 1;
        }
        assert_eq!(served, 10_000);
        let stats = cache.stats().unwrap();
        assert_eq!(stats.hits + stats.misses, 10_000);
    }
}
